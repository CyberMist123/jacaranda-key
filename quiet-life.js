function quietLife() {
  return QUIET_LIFE[typeof LANG === 'string' && QUIET_LIFE[LANG] ? LANG : 'zh'];
}

// 第 idx 句（idx 从 0 起，持续累加）：前几句按顺序，之后随机
function quietLineAt(idx) {
  const q = quietLife();
  if (idx < q.first.length) return q.first[idx];
  return q.pool[Math.floor(Math.random() * q.pool.length)];
}

// 打开弹窗时：23:50–23:59 用时间专属那句，否则返回 null（交给顺序/随机）
function quietLineForTime(now = new Date()) {
  if (now.getHours() !== 23 || now.getMinutes() < 50) return null;
  const q = quietLife();
  return now.getMinutes() === 56 ? q.at2356 : q.at235x;
}
